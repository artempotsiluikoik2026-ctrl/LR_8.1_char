// Дано літерний рядок, який містить послідовність символів s[0], ..., s[n], ...
// 1. Вияснити, чи є серед цих символів трійка сусідніх букв "OGO" або "AGA".
// 2. Замінити кожну трійку сусідніх букв "OGO" або "AGA" парою зірочок "**".

#define _CRT_SECURE_NO_WARNINGS // дозволяє використовувати strcpy без помилки-попередження
#include <iostream>
using namespace std;

bool Exist(char* s) // функція повертає true, якщо в рядку s є "OGO" або "AGA"
{
	if (strstr(s, "OGO") || strstr(s, "AGA"))  // strstr шукає підрядок: знайшла = адреса, не знайшла = 0
		return true;
	return false;
}

char* Change(char* s) // s = вказівник на початок рядка
{
	char* t = new char[strlen(s) + 1]; // новий рядок у пам'яті: стільки місць, скільки літер у s + 1 під '\0'
	char* p; // p = адреса літери 'O' або 'A', яку знайшли (поки порожня)
	int pos1 = 0, // pos1 = позиція початку пошуку
		pos2 = 0; // pos2 = допоміжний номер: де закінчилась оброблена частина
	*t = 0; // робимо t порожнім рядком ('\0' на початку), щоб strcat і strncat могли дописувати в його кінець
	while (p = strpbrk(s + pos1, "OA")) // шукаємо від місця pos1 найближчу літеру 'O' або 'A'; знайшли - заходимо в цикл
	{
		if (p[1] == 'G' && p[2] == *p) // чи це трійка? p[1] = наступна літера, p[2] = через одну; *p = сама літера, на яку вказує p
		{
			pos2 = p - s + 3; // pos2 = позиція наступного символа після трійки 
			strncat(t, s + pos1, pos2 - pos1 - 3); // дописуємо в t усе, що було ДО трійки (від pos1 до початку трійки)
			strcat(t, "**"); // дописуємо в t дві зірочки замість трійки
			pos1 = pos2; // далі шукаємо вже після трійки
		}
		else
		{
			pos2 = p - s + 1; // pos2 = позиція наступного символа після 'O' або 'A'
			strncat(t, s + pos1, pos2 - pos1); // дописуємо в t усе від pos1 до цієї літери включно
			pos1 = pos2; // далі шукаємо після цієї літери
		}
	}
	strcat(t, s + pos1); // цикл закінчився(O і A більше немає) : дописуємо в t кінець рядка від pos1 до кінця
	strcpy(s, t); // копіюємо готовий результат з t назад у s (щоб змінився і сам рядок)
	return t; // повертаємо адресу нового рядка
}

int main()
{
	char str[101]; // масив на 101 клітинку: з запасом під літери і '\0'
	cout << "Enter string:" << endl;
	cin.getline(str, 100); // читаємо весь рядок (з пробілами) у str, не більше 99 символів
	if (Exist(str))
		cout << "String contains OGO or AGA" << endl;
	else
		cout << "String does not contain OGO or AGA" << endl;
	char* result = Change(str); // міняємо рядок; result - адреса нового рядка
	cout << "Modified string (param) : " << str << endl; // str змінився через strcpy
	cout << "Modified string (result): " << result << endl; // результат, який повернула функція
	delete[] result; // повертаємо пам'ять, яку виділили через new у Change

	return 0;
}